export function getBackgroundEntry(
  id: string
): BackgroundsCatalogEntry | undefined {
  return backgroundsCatalog.find((e) => e.id === id)
}

export function backgroundViewHref(id: string) {
  return `/backgrounds/view/${id}`
}

export function getBackgroundAdjacent(id: string): {
  previous: BackgroundsCatalogEntry | null
  next: BackgroundsCatalogEntry | null
} {
  const index = backgroundsCatalog.findIndex((e) => e.id === id)
  if (index < 0) return { previous: null, next: null }
  return {
    previous: index > 0 ? backgroundsCatalog[index - 1]! : null,
    next:
      index < backgroundsCatalog.length - 1
        ? backgroundsCatalog[index + 1]!
        : null,
  }
}
